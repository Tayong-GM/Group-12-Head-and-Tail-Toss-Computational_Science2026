# ================= 1. AGGREGATE THE DATA =================
# Added "2" to the master dictionary
master_coins = {
    "1A": "", "1B": "", "2": "",
    "5A": "", "5B": "", 
    "10A": "", "10B": "", 
    "20": ""
}

for group_name, coins in group_data.items():
    for coin_name, coin_string in coins.items():
        if coin_name in master_coins:
            master_coins[coin_name] += coin_string 

# ================= 2. CALCULATE AND PLOT =================
def calculate_cumulative(flips_string):
    heads_cum = []
    tails_cum = []
    h_count, t_count = 0, 0
    for char in flips_string:
        if char == '1': h_count += 1
        elif char == '0': t_count += 1
        heads_cum.append(h_count)
        tails_cum.append(t_count)
    return list(range(1, len(flips_string) + 1)), heads_cum, tails_cum

print("--- FINAL CLASS TALLY ---")

for coin_name, combined_string in master_coins.items():
    if not combined_string: continue
    
    attempts, heads_cum, tails_cum = calculate_cumulative(combined_string)
    total_tosses = len(combined_string)
    total_heads = heads_cum[-1]
    total_tails = tails_cum[-1]
    
    print(f"Coin {coin_name}: {total_tosses} total tosses -> Heads: {total_heads} | Tails: {total_tails}")

    plt.figure(figsize=(10, 6)) 
    plt.plot(attempts, heads_cum, label='Total Heads', color='#1f77b4', linewidth=2)
    plt.plot(attempts, tails_cum, label='Total Tails', color='#ff7f0e', linestyle='--', linewidth=2)

    plt.title(f'MASTER CLASS DATA: Coin {coin_name} ({total_tosses} Tosses Total)', fontsize=14, fontweight='bold')
    plt.xlabel('Toss Number', fontsize=12)
    plt.ylabel('Cumulative Count', fontsize=12)
    plt.legend()
    plt.grid(True, linestyle=':', alpha=0.6)

    file_path = f"{folder_name}/Master_{coin_name}.png"
    plt.savefig(file_path, bbox_inches='tight', dpi=150)
    plt.close()

